# -------- Math Library -----------
import math

number = 16
sqrt = math.sqrt(number)

print(f"Square root of {number}: {sqrt}")




# Calculate the value of pi
pi = math.pi
print(f"Value of pi: {pi}")




# Calculate the sine of an angle (in radians)
angle = 30
sine = math.cos(angle)

print(f"Sine of {angle} radians: {sine}")