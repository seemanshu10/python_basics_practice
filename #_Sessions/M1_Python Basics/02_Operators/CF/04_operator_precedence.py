'''
PEMDAS Rule:
    P – Parentheses (Highest precedence)
    E – Exponentiation (**)
    M – Multiplication
    D – Division
    A – Addition
    S – Subtraction
'''

# P – Parentheses
result = (2 + 3) * 4
# result = 2 + 3 * 4

# ------------------------------ 

# E – Exponentiation
result = 2 ** 3 + 1 

# Chained exponentiation:
result = (2 ** 3) ** 2

# ------------------------------ 

# M – Multiplication
result = 5 * 4 + 6 

# ------------------------------ 

# D – Division
result = 20 / 4  
# result = 10 / 2 + 3 

# ------------------------------ 

# A – Addition
result = 10 - 2 + 3
# result = 5 + 2 - 3

# ------------------------------ 

# S – Subtraction
result = 10 - 2 + 3 