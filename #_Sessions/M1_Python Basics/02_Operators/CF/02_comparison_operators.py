'''
List of Comparison Operators are:
    ==: Equal to
    !=: Not equal to
    >: Greater than
    <: Less than
    >=: Greater than or equal to
    <=: Less than or equal to
'''

# Equal to
a = 10
b = 10

result = a == b
print(result)

# Not Equal to
result = a != b

# Greater than
result = a > b

# Less than
result = a < b

# Greater than or equal to
result = a >= b

# Less than or equal to
result = a <= b
