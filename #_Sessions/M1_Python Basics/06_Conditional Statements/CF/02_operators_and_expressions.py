#  ------------------- Comparison Operator ----------------

a = 10
b = 10

#  Using == (Equal to)
if a == b:
    print("a is equal to b")
else:
    print("a is not equal to b")


# Using !=
x = 15
y = 20

if x != y:
    print("x is not equal to y")
else:
    print("x is equal to y")


# Using >
num1 = 25
num2 = 20

if num1 > num2:
    print("num1 is greater than num2")
else:
    print("num1 is not greater than num2")


# Using <
value1 = 30
value2 = 40

if value1 < value2:
    print("value1 is less than value2")
else:
    print("value1 is not less than value2")


# Using >=
num_a = 50
num_b = 50

if num_a >= num_b:
    print("num_a is greater than or equal to num_b")
else:
    print("num_a is less than num_b")


# Using <=
age = 21
legal_age = 21

if age <= legal_age:
    print("Age is less than or equal to the legal age")
else:
    print("Age is greater than the legal age")



#  ------------------- Boolean Expressions ----------------

is_raining = True

if is_raining:
    print("Remember to take an umbrella!")
else:
    print("No need for an umbrella today.")