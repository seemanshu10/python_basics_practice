'''
 - Single line strings :
    - Single quotes (' ')
    - Double quotes (" ")

 - Multiple line strings :
    - Triple single quotes (''' ''')
    - Triple double quotes (""" """)
'''



# Double quote
string2 = "Python is fun!"


# single quote
string1 = 'Hello, World!'


# Triple single quote
multi_line_string = '''This is a multi-line string.
It can span across multiple lines.
Python will preserve the line breaks.'''


# Triple double quote
another_multi_line_string = """This is another way
to write a multi-line string.
Both methods work the same."""

print(string1)
print(string2)
print(multi_line_string)
print(another_multi_line_string)