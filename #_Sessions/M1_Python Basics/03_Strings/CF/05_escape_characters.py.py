# Problem Scenario
print("I am Ravi and i live in India.")





# \t
print("I am\tRavi and i live in India.")


# \n
print("I am\nRavi and i live in India.")


# \'
print('I am Ravi and I\'m learning Python.')


# \"
print("He said, \"Python is awesome!\"")


# \\
print("This is a backslash: \\")













'''
Common Escape Characters:
    \t   → Tab (horizontal space)
    \n   → New Line
    \'   → Single Quote
    \"   → Double Quote
    \\   → Backslash
'''