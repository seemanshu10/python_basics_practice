# get()
person = {"name": "Alice", "age": 25}
age = person.get("age")


# keys()
person = {"name": "Alice", "age": 25, "city": "London"}
keys = person.keys()


# values()
person = {"name": "Alice", "age": 25, "city": "London"}
values = person.values()


# items()
person = {"name": "Alice", "age": 25, "city": "London"}
items = person.items()


# update()
person = {"name": "Alice", "age": 25}
person.update({"city": "London", "age": 26})


# pop()
person = {"name": "Alice", "age": 25, "city": "London"}
age = person.pop("age")


# clear()
person = {"name": "Alice", "age": 25, "city": "London"}
person.clear()




