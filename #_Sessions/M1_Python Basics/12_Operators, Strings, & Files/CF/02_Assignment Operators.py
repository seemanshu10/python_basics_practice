#---------------- Basic assignment (=) ----------------
a = 10
print("Basic assignment =", a)  # Output: 10



#---------------- Add & assign (+=) -------------------
a = 10
a += 5
print("Add & assign (+=) =", a)  # Output: 15



#---------------- Subtract & assign (-=) --------------
a = 15
a -= 3
print("Subtract & assign (-=) =", a)  # Output: 12



#---------------- Multiply & assign (*=) --------------
a = 12
a *= 2
print("Multiply & assign (*=) =", a)  # Output: 24



#---------------- Divide & assign (/=) ----------------
a = 24
a /= 4
print("Divide & assign (/=) =", a)  # Output: 6.0



#---------------- Floor divide & assign (//=) ---------
a = 25
a //= 4
print("Floor divide & assign (//=) =", a)  # Output: 6



#---------------- Modulus & assign (%=) ---------------
a = 25
a %= 5
print("Modulus & assign (%=) =", a)  # Output: 0



#---------------- Exponentiate & assign (**=) ---------
a = 5
a **= 2
print("Exponentiate & assign (**=) =", a)  # Output: 25