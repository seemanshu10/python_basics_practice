#---------------- Unary Plus (+) ----------------------
a = 10
print("Unary Plus (+a):", +a)  




#---------------- Unary Minus (-) ---------------------
b = 10
print("Unary Minus (-b):", -b)  # Output: -10 


c = -15
print("Unary Minus (-c):", -c)  # Output: 15 




#---------------- Bitwise NOT (~) ---------------------
p = 5
print("Bitwise NOT (~p):", ~p)   


q = -10
print("Bitwise NOT (~q):", ~q)   

