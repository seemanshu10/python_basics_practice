#---------------- Adding int and float -----------------
x = 8      # int
y = 4.5    # float
result = x + y

print("Result of int + float:", result)       # 12.5
print("Type of result:", type(result))        # <class 'float'>



#---------------- Boolean in arithmetic ----------------
a = False   # Boolean (internally 0)
b = 10      # int

print("False + 10 =", a + b)                  # 10
print("Type:", type(a + b))                   # <class 'int'>



#---------------- Multiplying float and int -----------
length = 7    # int
width = 2.5   # float
area = length * width

print("Area =", area)                         # 17.5
print("Type:", type(area))                    # <class 'float'>
