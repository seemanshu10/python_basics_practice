# ---------------- List Indexing -------------------

animals = ["lion", "tiger", "bear", "wolf"]

# Accessing elements
print(animals[0]) 
print(animals[2])  


fruits = ["apple", "banana", "cherry", "date"]

# Positive Indexing
print(fruits[0])  
print(fruits[2])  

# Negative Indexing
print(fruits[-1])
print(fruits[-3]) 



# ----------- Order of Preservation -----------------

my_list = ["apple", "banana", "cherry"]

# Accessing elements by their index
print(my_list[0])  
print(my_list[1])  
print(my_list[2])  


# ----------- Duplicates are Allowed -----------------

my_list = ["apple", "banana", "apple", "cherry", "banana"]

# Accessing Duplicates:
print(my_list[0])
print(my_list[2])
print(my_list[1])
print(my_list[4])

