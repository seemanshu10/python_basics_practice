
# iterating with String
word = "Python"

for char in word:
    print(char)


# iterating with list
numbers = [1, 2, 3, 4, 5]

for number in numbers:
    print(number)


# iterating with Dictionary
student_grades = {'Alice': 85, 'Bob': 92, 'Charlie': 78}

for student in student_grades:
    print(student)


